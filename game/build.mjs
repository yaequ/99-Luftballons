import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const gameDirectory = fileURLToPath(new URL('./', import.meta.url));
const modules = new Map();
const visiting = new Set();

function bundleModule(id) {
  if (modules.has(id)) return;
  if (visiting.has(id)) throw new Error(`Circular import: ${id}`);
  visiting.add(id);
  let source = readFileSync(path.join(gameDirectory, id), 'utf8');
  source = source.replace(/^import (.+?) from ['"](.+?)['"];\r?$/gm, (_, binding, specifier) => {
    if (!specifier.startsWith('.')) throw new Error(`Unsupported import: ${specifier}`);
    const dependency = path.posix.normalize(path.posix.join(path.posix.dirname(id), specifier));
    bundleModule(dependency);
    const local = binding.startsWith('* as ') ? binding.slice(5) : binding;
    return `const ${local} = modules[${JSON.stringify(dependency)}];`;
  });
  let exports = '';
  source = source.replace(/^export \{ ([^}]+) \};\r?$/gm, (_, names) => {
    exports = names;
    return '';
  });
  if (/^\s*(import|export)\s/m.test(source)) throw new Error(`Unsupported module syntax: ${id}`);
  modules.set(id, `modules[${JSON.stringify(id)}] = (() => {\n${source.trim()}\nreturn { ${exports} };\n})();`);
  visiting.delete(id);
}

bundleModule('game.js');
const output = `// Generated by game/build.mjs. Edit game.js and modules/ instead.\n(() => {\n'use strict';\nconst modules = {};\n\n${[...modules.values()].join('\n\n')}\n})();\n`;
writeFileSync(path.join(gameDirectory, 'game.bundle.js'), output);
console.log(`Built game.bundle.js from ${modules.size} modules.`);
